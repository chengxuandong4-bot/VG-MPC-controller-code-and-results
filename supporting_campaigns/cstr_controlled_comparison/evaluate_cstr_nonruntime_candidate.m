function evaluate_cstr_nonruntime_candidate(input_path, output_path)
% Additive MATLAB bridge for cstr_nonruntime_score_v1_minimal.
    try
        request = jsondecode(fileread(input_path));
        root = fileparts(mfilename('fullpath')); deepseek_root = fileparts(root);
        addpath(fullfile(deepseek_root,'benchmark_lightweight'));
        addpath(fullfile(deepseek_root,'benchmark_lightweight','src'));
        c = config_lightweight('single'); p = c.init_params();
        baseline = c.single.initial_candidate(p,[]);
        if strcmp(request.mode,'baseline')
            candidate = baseline;
        elseif strcmp(request.mode,'candidate')
            space = jsondecode(fileread(fullfile(root,'search_space_cstr_reduced.json')));
            [candidate,~] = construct_cstr_candidate(baseline,request.parameters,space);
        else
            error('IntermediateBridge:Mode','Unsupported bridge mode.');
        end
        ev = evaluate_cstr_candidate(c,p,candidate);
        out = pack_nonruntime(ev,candidate);
        out.bridge_success = true;
    catch
        out = failure_record();
    end
    fid = fopen(output_path,'w','n','UTF-8');
    assert(fid>0,'Cannot write bridge output.'); cleanup = onCleanup(@()fclose(fid));
    fprintf(fid,'%s',jsonencode(out,'PrettyPrint',true)); clear cleanup;
end

function out = pack_nonruntime(ev,candidate)
    failed = ~ev.execution_success;
    [raw,status] = minimal_nonruntime_score(ev.metrics,failed);
    penalty = ev.violation_penalty;
    selection = raw - penalty;
    out = struct( ...
        'candidate_id',ev.candidate_id,'candidate',candidate, ...
        'execution_success',ev.execution_success,'result_failed',failed, ...
        'metrics',ev.metrics,'avg_controller_time_ms',ev.metrics(6), ...
        'accepted',ev.accepted, ...
        'raw_score_nonruntime',raw,'raw_score_nonruntime_status',status, ...
        'violation_penalty',penalty,'selection_score_nonruntime',selection, ...
        'selection_score_nonruntime_status',status, ...
        'simulation_duration_s',ev.duration_s, ...
        'matlab_version',version, ...
        'score_protocol_version','cstr_nonruntime_score_v1_minimal', ...
        'acceptance_protocol_version','cstr_acceptance_v1_runtime_independent', ...
        'adapter_version','cstr_nonruntime_matlab_adapter_v1');
end

function [score,status] = minimal_nonruntime_score(metrics,failed)
    if failed
        score = -Inf; status = 'negative_infinity_failure'; return;
    end
    selected = metrics([1 2 3 4 5 7 8]);
    if any(isinf(selected)|isnan(selected))
        score = -Inf; status = 'negative_infinity_nonfinite_metric'; return;
    end
    phi = max(0,1-selected./(1+selected));
    score = sum(phi)/7; status = 'finite';
end

function out = failure_record()
    out = struct( ...
        'bridge_success',false,'candidate_id','','candidate',struct(), ...
        'execution_success',false,'result_failed',true,'metrics',Inf(1,8), ...
        'avg_controller_time_ms',NaN, ...
        'accepted',false,'raw_score_nonruntime',-Inf, ...
        'raw_score_nonruntime_status','negative_infinity_failure', ...
        'violation_penalty',100,'selection_score_nonruntime',-Inf, ...
        'selection_score_nonruntime_status','negative_infinity_failure', ...
        'simulation_duration_s',0, ...
        'matlab_version',version, ...
        'score_protocol_version','cstr_nonruntime_score_v1_minimal', ...
        'acceptance_protocol_version','cstr_acceptance_v1_runtime_independent', ...
        'adapter_version','cstr_nonruntime_matlab_adapter_v1');
end
