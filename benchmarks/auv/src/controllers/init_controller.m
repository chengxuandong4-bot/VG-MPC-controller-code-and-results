function controller = init_controller(type, params, config)
controller = struct();
controller.type = lower(type);
controller.name = config.name;
controller.label = config.label;
controller.config = config;

switch controller.type
    case 'paper_is_sat'
        controller.K = params.paper.K_is_sat;
        controller.state = struct();

    case 'adaptive_fta'
        controller.K_nominal = params.paper.K_is_sat;
        controller.state = struct( ...
            'step_count', 0, ...
            'prev_x', params.sim.x0, ...
            'prev_u', zeros(4, 1), ...
            'h_hat', ones(4, 1), ...
            'P', eye(4) * config.rls_cov0, ...
            'tau_meas_hat', zeros(3, 1), ...
            'residual_hat', zeros(3, 1), ...
            'int_vel', zeros(2, 1), ...
            'int_psi', 0.0, ...
            'int_r', 0.0, ...
            'prev_r_cmd', 0.0, ...
            'last_u_target', zeros(4, 1), ...
            'event_hold_steps', 0, ...
            'event_refresh_count', 0, ...
            'event_hold_count', 0);

    otherwise
        error('Unknown controller type: %s', type);
end
end
