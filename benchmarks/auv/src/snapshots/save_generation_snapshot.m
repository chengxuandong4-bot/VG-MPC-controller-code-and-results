function save_generation_snapshot(rootDir, generationIndex, config, metrics)
snapshotName = sprintf('gen_%02d_%s', generationIndex, config.name);
snapshotDir = fullfile(rootDir, 'generation_snapshots', snapshotName);

if exist(snapshotDir, 'dir')
    suffixId = 1;
    while exist(snapshotDir, 'dir')
        snapshotDir = fullfile(rootDir, 'generation_snapshots', sprintf('%s_rerun_%02d', snapshotName, suffixId));
        suffixId = suffixId + 1;
    end
end
mkdir(snapshotDir);

copyfile(fullfile(rootDir, 'run_fault_tolerant_adaptive.m'), fullfile(snapshotDir, 'run_fault_tolerant_adaptive.m'));
copyfile(fullfile(rootDir, 'src'), fullfile(snapshotDir, 'src'));

meta = struct( ...
    'generation_index', generationIndex, ...
    'name', config.name, ...
    'label', config.label, ...
    'description', config.description, ...
    'snapshot_created_at', char(datetime('now', 'Format', 'yyyy-MM-dd HH:mm:ss')));

write_json(fullfile(snapshotDir, 'meta_snapshot.json'), meta);
write_json(fullfile(snapshotDir, 'config_snapshot.json'), config);
write_json(fullfile(snapshotDir, 'metrics_snapshot.json'), metrics);

write_text(fullfile(snapshotDir, 'README.md'), compose_readme(config, rootDir));
write_text(fullfile(snapshotDir, 'OVERVIEW.md'), compose_overview(generationIndex, config, metrics));
end

function write_json(path, value)
fid = fopen(path, 'w');
cleanupObj = onCleanup(@() fclose(fid));
fprintf(fid, '%s', jsonencode(value));
end

function write_text(path, textValue)
fid = fopen(path, 'w');
cleanupObj = onCleanup(@() fclose(fid));
fprintf(fid, '%s', textValue);
end

function textValue = compose_readme(config, rootDir)
rootDirCmd = strrep(rootDir, '\', '/');
textValue = sprintf(['# Generation Snapshot\n\n' ...
    'Run in MATLAB:\n\n' ...
    '```matlab\n' ...
    'cd(''%s'');\n' ...
    'summary = run_fault_tolerant_adaptive();\n' ...
    '```\n\n' ...
    'Snapshot label: `%s`\n'], rootDirCmd, config.name);
end

function textValue = compose_overview(generationIndex, config, metrics)
textValue = sprintf([ ...
    '# Generation Snapshot\n\n' ...
    '- generation_index: %d\n' ...
    '- name: %s\n' ...
    '- label: %s\n' ...
    '- description: %s\n\n' ...
    '## Key Metrics\n' ...
    '- integral_error: %.6f\n' ...
    '- integral_error_raw: %.6f\n' ...
    '- rms_tracking_error: %.6f\n' ...
    '- max_tracking_error: %.6f\n' ...
    '- control_energy: %.6f\n' ...
    '- fault1_peak_error: %.6f\n' ...
    '- fault2_peak_error: %.6f\n' ...
    '- avg_controller_time_ms: %.6f\n' ...
    '- simulation_runtime: %.6f\n' ...
    '- health_estimation_mae_act2: %.6f\n' ...
    '- health_estimation_mae_act3: %.6f\n' ...
    '- failed: %d\n'], ...
    generationIndex, ...
    config.name, ...
    config.label, ...
    config.description, ...
    metrics.integral_error, ...
    metrics.integral_error_raw, ...
    metrics.rms_tracking_error, ...
    metrics.max_tracking_error, ...
    metrics.control_energy, ...
    metrics.fault1_peak_error, ...
    metrics.fault2_peak_error, ...
    metrics.avg_controller_time_ms, ...
    metrics.simulation_runtime, ...
    metrics.health_estimation_mae_act2, ...
    metrics.health_estimation_mae_act3, ...
    metrics.failed);
end
