function params = paper_auv5_params()
params = struct();

params.model = struct( ...
    'm', 500.0, ...
    'Jz', 300.0, ...
    'Xu', 6.106, ...
    'Xuu', 5.0, ...
    'Yv', 11.203, ...
    'Yvv', 10.114, ...
    'Nr', 210.0, ...
    'Nrr', 3.0);

params.actuator = struct( ...
    'pG', 38.0, ...
    'alpha', [pi/4, -pi/4, -pi/4, pi/4], ...
    'lx', [-1.01, -1.01, 1.01, 1.01], ...
    'ly', [-0.353, 0.353, -0.353, 0.353], ...
    'u_min', -ones(4, 1), ...
    'u_max', ones(4, 1));

G = zeros(3, 4);
for idx = 1:4
    alpha = params.actuator.alpha(idx);
    lx = params.actuator.lx(idx);
    ly = params.actuator.ly(idx);
    pG = params.actuator.pG;
    G(:, idx) = pG * [ ...
        sin(alpha); ...
        cos(alpha); ...
        -sin(alpha) * ly + cos(alpha) * lx];
end
params.actuator.G = G;

params.sim = struct( ...
    'Ts', 0.01, ...
    'num_steps', 12000, ...
    'x0', ones(5, 1) + 2.0, ...
    'fault_time_1', 40.0, ...
    'fault_time_2', 80.0, ...
    'fault_level', 0.10, ...
    'tracked_state_count', 4, ...
    'paper_ref_x4', 0.20);

params.paper = struct();
params.paper.K_is_sat = [ ...
    -50.98781602, -48.44657148, 591.40640211, 114.77740694, 5.48530836; ...
     45.53251654, -45.81310304, 540.44618274, 107.24054371, 5.12516529; ...
     46.94591829, -47.94972841, -540.43310069, -104.29568136, -4.98424422; ...
    -41.54824799, -44.53343709, -492.38032439, -96.35366138, -4.60431652];
end
